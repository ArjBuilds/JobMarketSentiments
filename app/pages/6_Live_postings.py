"""Live postings page: the backend's real-time aggregates, over its WebSocket.

Not part of the 82-company library and reads nothing from SQLite. The
browser connects straight to backend.api (uvicorn backend.api:app), so the
panel updates as the worker stores postings, without a Streamlit rerun.
With the API down the panel says "Not available". The API's address is
BACKEND_WS_URL, ws://localhost:8000 by default.
"""

import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import streamlit as st  # noqa: E402
import streamlit.components.v1 as components  # noqa: E402

from app.state import init_state  # noqa: E402
from app.ui.charts import ACCENT  # noqa: E402
from jmsa.display import NOT_AVAILABLE  # noqa: E402

init_state()

WS_URL = os.getenv("BACKEND_WS_URL", "ws://localhost:8000")
DATASETS = {"Greenhouse boards": "live", "Synthetic (load test)": "synthetic"}

# Plain JS, no libraries: one WebSocket, a total, a bar per day and the top
# skills, redrawn on every message. Reconnects every 3 s if the API stops.
PANEL = """
<div id="panel" style="font-family: sans-serif; color: #808495; font-size: 14px">
  <div id="status">Connecting…</div>
  <div id="body" style="display:none">
    <div id="label" style="font-weight:600; margin: 4px 0"></div>
    <div style="font-size: 28px; color: inherit" id="total"></div>
    <div style="margin-top: 10px">Postings per day, last __DAYS__ days</div>
    <svg id="days" width="100%" height="90" style="margin-top:4px"></svg>
    <div style="margin-top: 10px">Top skills, same days</div>
    <div id="skills"></div>
  </div>
</div>
<script>
const url = __URL__, accent = __ACCENT__, missing = __MISSING__;
const fmt = n => n.toLocaleString("en-GB");
const date = d => new Date(d + "T00:00:00Z").toLocaleDateString("en-GB",
  {day: "numeric", month: "short", year: "numeric", timeZone: "UTC"});
function draw(m) {
  document.getElementById("status").textContent =
    "Updated " + new Date(m.sent_at).toLocaleTimeString("en-GB") + (m.type === "update" ? " · live" : "");
  document.getElementById("body").style.display = "block";
  document.getElementById("label").textContent = m.synthetic
    ? "SYNTHETIC DATA: generated for load testing, not real postings"
    : "Greenhouse public job boards · 15 employers, not in the library";
  document.getElementById("total").textContent = fmt(m.total_postings) + " postings stored";
  const svg = document.getElementById("days"), w = svg.clientWidth || 600, n = m.volume.length;
  const max = Math.max(1, ...m.volume.map(v => v.postings)), bw = w / Math.max(n, 1);
  svg.innerHTML = m.volume.map((v, i) => {
    const h = Math.max(1, 80 * v.postings / max);
    return `<rect x="${i * bw + 1}" y="${85 - h}" width="${bw - 2}" height="${h}" fill="${accent}">` +
           `<title>${date(v.day)}: ${fmt(v.postings)}</title></rect>`;
  }).join("");
  const top = Math.max(1, ...m.top_skills.map(s => s.postings));
  document.getElementById("skills").innerHTML = m.top_skills.map(s =>
    `<div style="display:flex; align-items:center; gap:8px; margin:3px 0">
       <span style="width:170px">${s.skill}</span>
       <span style="height:12px; width:${60 * s.postings / top}%; background:${accent}"></span>
       <span>${fmt(s.postings)}</span></div>`).join("") || missing;
}
function connect() {
  const ws = new WebSocket(url);
  ws.onmessage = e => draw(JSON.parse(e.data));
  ws.onclose = () => {
    document.getElementById("status").textContent = missing + ": the live API is not running.";
    document.getElementById("body").style.display = "none";
    setTimeout(connect, 3000);
  };
}
connect();
</script>
"""

st.title("Live postings")
choice = st.radio("Data", list(DATASETS), horizontal=True,
                  help="Synthetic data is generated for load testing and needs the ClickHouse store.")
dataset = DATASETS[choice]
st.caption("Greenhouse job board API · updated as postings are stored" if dataset == "live"
           else "SYNTHETIC DATA · generated by backend.generate, not real postings")
with st.container(border=True):
    components.html(
        PANEL.replace("__URL__", json.dumps(f"{WS_URL}/ws/aggregates?dataset={dataset}"))
             .replace("__ACCENT__", json.dumps(ACCENT))
             .replace("__MISSING__", json.dumps(NOT_AVAILABLE))
             .replace("__DAYS__", "30"),
        height=520,
    )
